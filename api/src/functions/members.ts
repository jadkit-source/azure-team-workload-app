import { withAuthentication } from "../shared/auth";
import { app, HttpRequest, HttpResponseInit, InvocationContext } from "@azure/functions";
import { TableClient } from "@azure/data-tables";

export async function members(
    request: HttpRequest,
    context: InvocationContext
): Promise<HttpResponseInit> {
    const connection = process.env.TABLES_CONNECTION_STRING;

    if (!connection?.trim()) {
        return {
            status: 503,
            jsonBody: { error: "Table Storage is not configured." }
        };
    }

    try {
        const memberClient = TableClient.fromConnectionString(connection, "Members");
        const taskClient = TableClient.fromConnectionString(connection, "WorkItems");

        const team: {
            memberId: string;
            displayName: string;
            activeTasks: number;
            doneLast30Days: number;
        }[] = [];

        for await (const member of memberClient.listEntities({
            queryOptions: {
                filter: "PartitionKey eq 'team:default' and Enabled eq true"
            }
        })) {
            team.push({
                memberId: String(member.MemberId),
                displayName: String(member.DisplayName),
                activeTasks: 0,
                doneLast30Days: 0
            });
        }

        // Use the immutable completion event to credit the person who
        // actually completed the task, not its current owner.
        const cutoff = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString();
        const completedTasks = new Map<string, { completedAt: string; completedBy: string }>();
        const doneCounts = new Map<string, number>();

        const counts = new Map<string, number>();
        let unassigned = 0;
        let totalActive = 0;

        for await (const task of taskClient.listEntities({
            queryOptions: {
                filter: "PartitionKey eq 'team:default' and EntityType eq 'Task'"
            }
        })) {
            if (task.Status === "Done" &&
                typeof task.TaskId === "string" &&
                typeof task.CompletedAt === "string" &&
                task.CompletedAt >= cutoff) {
                completedTasks.set(task.TaskId, {
                    completedAt: task.CompletedAt,
                    completedBy: String(task.CompletedBy || "")
                });
            }

            if (
                task.Archived === true ||
                (task.Status !== "Open" && task.Status !== "In Progress")
            ) {
                continue;
            }

            totalActive++;

            const ownerId = String(task.OwnerId || "");

            if (!ownerId) {
                unassigned++;
            } else {
                counts.set(ownerId, (counts.get(ownerId) || 0) + 1);
            }
        }

        // TaskCompleted is the actual audit event generated by changeStatus.
        // A currently reopened task is absent from completedTasks. Matching
        // CompletedAt prevents counting older completions of the same task.
        const creditedTaskIds = new Set<string>();
        for await (const event of taskClient.listEntities({
            queryOptions: {
                filter: "PartitionKey eq 'team:default' and EntityType eq 'Event' and EventType eq 'TaskCompleted'"
            }
        })) {
            const taskId = String(event.TaskId || "");
            const completed = completedTasks.get(taskId);
            const occurredAt = String(event.OccurredAtUtc || "");
            const actor = String(event.ActorMemberId || "");
            if (!completed || creditedTaskIds.has(taskId) ||
                occurredAt !== completed.completedAt ||
                actor !== completed.completedBy || !actor) {
                continue;
            }
            creditedTaskIds.add(taskId);
            doneCounts.set(actor, (doneCounts.get(actor) || 0) + 1);
        }

        for (const member of team) {
            member.activeTasks = counts.get(member.memberId) || 0;
            member.doneLast30Days = doneCounts.get(member.memberId) || 0;
        }

        team.sort((a, b) =>
            a.activeTasks - b.activeTasks ||
            a.displayName.localeCompare(b.displayName)
        );

        const enabledIds = new Set(team.map(member => member.memberId));
        let inactiveOwnerTasks = 0;

        for (const [ownerId, count] of counts) {
            if (!enabledIds.has(ownerId)) {
                inactiveOwnerTasks += count;
            }
        }

        return {
            status: 200,
            jsonBody: {
                members: team,
                unassigned,
                inactiveOwnerTasks,
                totalActive
            }
        };
    } catch (error) {
        context.error("Failed to read team workload", error);

        return {
            status: 500,
            jsonBody: { error: "Unable to read team workload." }
        };
    }
}

app.http("members", {
    methods: ["GET"],
    authLevel: "anonymous",
    handler: withAuthentication(members)
});
